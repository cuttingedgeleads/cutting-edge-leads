import {spawn} from 'node:child_process';
import {mkdirSync,writeFileSync,readdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
const cwd=fileURLToPath(new URL('..',import.meta.url));
const env={};
for(const [k,v] of Object.entries(process.env))if(/^(path|systemroot|windir|comspec|temp|tmp|home|userprofile|localappdata|appdata|programfiles|programfiles\(x86\)|systemdrive|pathext)$/i.test(k))env[k]=v;
if([cwd,join(cwd,'prisma')].some(d=>readdirSync(d).some(f=>/^\.env(?:\.|$)/.test(f)&&f!=='.env.example')))throw Error('LOCAL_DOTENV_FORBIDDEN');
const mode=process.argv[2]||'unit',label=process.argv[3]||mode;
if(!/^[a-z0-9-]+$/.test(label))throw Error('EVIDENCE_LABEL');
const evidence=join(cwd,'.handoff-qa');mkdirSync(evidence,{recursive:true});
const files=readdirSync(join(cwd,'tests')).filter(f=>/^import-.*\.test\.ts$/.test(f)&&!f.includes('-db.')&&!f.includes('-browser.'));
let args;
if(mode==='unit')args=['--import','tsx','--test','--test-reporter=tap',...files.map(f=>'tests/'+f)];
else if(mode==='tsc')args=['node_modules/typescript/bin/tsc','--noEmit'];
else if(mode==='db')args=['--import','tsx','--test','--test-reporter=tap',...readdirSync(join(cwd,'tests')).filter(f=>/^import-.*db\.test\.ts$/.test(f)).map(f=>'tests/'+f)];
else if(mode==='migrate')args=['node_modules/prisma/build/index.js','migrate','deploy'];
else if(mode==='generate')args=['node_modules/prisma/build/index.js','generate'];
else if(mode==='install-browsers')args=['node_modules/playwright/cli.js','install','chromium','webkit'];
else if(mode==='browser')args=['tests/run-import-browser.mjs'];
else if(mode==='browser-production')args=['tests/run-import-browser.mjs','production'];
else if(mode==='build')args=['node_modules/next/dist/bin/next','build','--webpack'];
else if(mode==='init')args=['tests/init-import-db.mjs'];
else throw Error('Unknown mode');
if(process.env.IMPORT_QA_PLAYWRIGHT_DRIVER)env.IMPORT_QA_PLAYWRIGHT_DRIVER=process.env.IMPORT_QA_PLAYWRIGHT_DRIVER;
Object.assign(env,{NODE_ENV:mode==='build'?'production':'test',NEXT_TELEMETRY_DISABLED:'1',DATABASE_URL:'postgresql://handoff_qa@127.0.0.1:55581/ce_leads_handoff_qa'});
const database=new URL(env.DATABASE_URL);
if(database.hostname!=='127.0.0.1'||database.port!=='55581'||database.username!=='handoff_qa'||database.password||database.pathname!=='/ce_leads_handoff_qa')throw Error('LOCAL_DATABASE_GUARD');
const child=spawn(process.execPath,args,{cwd,env,stdio:['ignore','pipe','pipe']});
let output=JSON.stringify({command:[process.execPath,...args]})+'\n';
const log=b=>{output+=b.toString();writeFileSync(join(evidence,label+'.log'),output);process.stdout.write(b);};child.stdout.on('data',log);child.stderr.on('data',log);
const code=await new Promise(resolve=>{child.on('error',e=>{log(String(e));resolve(1);});child.on('close',c=>resolve(c??1));});
writeFileSync(join(evidence,label+'.log'),output+'\nEXIT '+code+'\n');process.exitCode=code;
